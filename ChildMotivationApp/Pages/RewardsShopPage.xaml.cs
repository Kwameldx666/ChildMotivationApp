    private void ApplyFilter(string filter)
    {
        if (filter == "???")
        {
            RewardsCollection.ItemsSource = Items;
            return;
        }

        RewardsCollection.ItemsSource = new ObservableCollection<RewardItem>(
            Items.Where(i => string.Equals(i.Category, filter, StringComparison.OrdinalIgnoreCase))
        );
    }
